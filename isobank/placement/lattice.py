"""
isobank.lattice
===============

Lattice template placement in the flow's latent space.

Greedy random packing is simple and robust but intrinsically over-dense:
its covering density exceeds the optimal lattice covering by a factor
~2-3x in moderate dimensions. In a curved parameter space lattice
placement is unavailable (no global flat coordinates) — but the isometric
flow's latent space is flat by construction, so the classical optimum
applies: place the A*_D lattice (the thinnest known lattice covering in
low dimensions, Conway & Sloane) scaled so its covering radius equals
r_z, and map the lattice sites back to physical space through the flow's
inverse.

The lattice basis is scaled using an EMPIRICALLY measured covering radius
(max distance of random probes to the lattice), so a suboptimal basis
degrades efficiency, never coverage.
"""

import sys
import numpy as np
import torch
from scipy.spatial import cKDTree

__all__ = ['an_star_basis', 'covering_radius', 'lattice_placement']

####################################################################################################################

def an_star_basis(d):
	"""
	Generator matrix (rows = basis vectors) of the A*_d lattice, expressed
	in d-dimensional coordinates. Construction (Conway & Sloane): A*_d lives
	in the hyperplane sum(x)=0 of R^{d+1} and is generated by
	v_i = e_i - (1,...,1)/(d+1), i = 1..d  (Gram = I - J/(d+1), whose
	determinant 1/(d+1) is the correct dual-lattice cell volume). The basis
	is expressed in an orthonormal frame of the hyperplane.
	"""
	B = np.eye(d, d + 1) - 1.0 / (d + 1)   # rows: e_i - 1/(d+1)

	#orthonormal frame of the hyperplane sum(x)=0
	P = np.eye(d + 1) - np.ones((d + 1, d + 1)) / (d + 1)
	Q, _ = np.linalg.qr(P[:, :d])          # d+1 x d, columns span the hyperplane
	return B @ Q                            # (d, d)

def covering_radius(basis, n_probe=200_000, seed=0):
	"""
	Empirical covering radius of the lattice with the given basis: the max
	distance from random points (drawn in a few central cells) to the
	nearest lattice site. Overestimates slightly (safe direction).
	"""
	d   = basis.shape[0]
	rng = np.random.default_rng(seed)
	#probes uniform in the fundamental parallelepiped (all cells identical)
	frac   = rng.uniform(0, 1, (n_probe, d))
	probes = frac @ basis
	#lattice sites within a couple of cells of the origin
	rng_int = np.arange(-2, 4)
	mesh    = np.stack(np.meshgrid(*[rng_int] * d, indexing='ij'), -1).reshape(-1, d)
	sites   = mesh @ basis
	tree    = cKDTree(sites)
	dd, _   = tree.query(probes, k=1, workers=-1)
	return float(dd.max())

####################################################################################################################

def lattice_placement(flow, r_z, lo, hi, embed_fn=None, valid_fn=None,
                      n_image_probe=2_000_000, slab_batch=2_000_000,
                      seed=0, fill_boundary=True, fill_batch=20_000,
                      fill_stop_acceptance=0.01, verbose=True):
	"""
	Cover the latent image of the parameter space with an A*_D lattice of
	covering radius ``r_z`` and map the sites back to physical space.

	Steps:
	  1. probe the z-image with uniform physical samples (defines both the
	     bounding box and an occupancy cloud);
	  2. scale the A*_D basis so its empirical covering radius is r_z;
	  3. enumerate lattice sites over the bounding box in slabs, keeping
	     only sites within r_z of the occupancy cloud (sites farther away
	     cover no physical point);
	  4. invert the flow at the kept sites; keep those landing inside the
	     physical boundaries (sites outside are dropped, never clamped);
	  5. optionally fill the boundary shell — which a rigid lattice cannot
	     conform to — with a short stochastic pass seeded by the lattice
	     ("geometric + stochastic" hybrid placement).

	Returns
	-------
		templates: :class:`~numpy:numpy.ndarray`
			(N, D) physical-space template coordinates
	"""
	if embed_fn is None: embed_fn = lambda t: t
	rng = np.random.default_rng(seed)
	D_theta = len(lo)

		#1. probe the z-image
	if verbose: print(f"Probing the latent image with {n_image_probe:,} points...")
	probes_th = rng.uniform(lo, hi, (n_image_probe, D_theta)).astype(np.float32)
	if valid_fn is not None:
		probes_th = probes_th[valid_fn(probes_th)]
	z_chunks = []
	for i in range(0, len(probes_th), 200_000):
		with torch.no_grad():
			z, _ = flow(embed_fn(torch.from_numpy(probes_th[i:i+200_000])))
		z_chunks.append(z.numpy())
	z_probe = np.vstack(z_chunks)
	D = z_probe.shape[1]
	z_lo, z_hi = z_probe.min(0) - 2 * r_z, z_probe.max(0) + 2 * r_z
	probe_tree = cKDTree(z_probe)
	if verbose:
		print(f"  image bbox widths: {np.round(z_hi - z_lo, 2)}")
		sys.stdout.flush()

		#2. scale the lattice
	basis = an_star_basis(D)
	R0    = covering_radius(basis)
	basis *= (r_z / R0)
	if verbose:
		print(f"A*_{D} basis scaled: covering radius {R0:.4f} -> {r_z:.4f}  "
		      f"(cell volume {abs(np.linalg.det(basis)):.3e})")
		print(f"  bbox/cell volume ratio: "
		      f"{np.prod(z_hi - z_lo)/abs(np.linalg.det(basis)):.3e} sites to enumerate")
		sys.stdout.flush()

		#3. probe-seeded enumeration: candidate sites are generated only in
		#the neighbourhood of the mapped probe cloud (a bounding-box sweep
		#would blow up for anisotropic images). Every lattice site within
		#r_z of a probe is reachable from that probe's base cell plus a
		#bounded integer offset.
	inv_basis = np.linalg.inv(basis)
	cell_diag = 0.5 * np.linalg.norm(basis, axis=1).sum()
	off_range = np.arange(-3, 4)
	offs = np.stack(np.meshgrid(*[off_range] * D, indexing='ij'), -1).reshape(-1, D)
	offs = offs[np.linalg.norm(offs @ basis, axis=1) <= r_z + cell_diag]
	if verbose:
		print(f"  probe-seeded enumeration: {len(offs)} integer offsets per probe")
		sys.stdout.flush()

	site_set = set()
	base_int = np.rint(z_probe @ inv_basis).astype(np.int64)
	base_int = np.unique(base_int, axis=0)
	for o in offs:
		cand = base_int + o
		site_set.update(map(bytes, np.ascontiguousarray(cand)))
	ints = np.frombuffer(b''.join(site_set), dtype=np.int64).reshape(-1, D)
	if verbose:
		print(f"  {len(base_int):,} occupied base cells -> {len(ints):,} candidate sites")
		sys.stdout.flush()

	kept_z = []
	for i in range(0, len(ints), slab_batch):
		sites = (ints[i:i+slab_batch] @ basis).astype(np.float64)
		dd, _ = probe_tree.query(sites, k=1, workers=-1)
		kept_z.append(sites[dd <= r_z])
	kept_z = np.vstack(kept_z) if kept_z else np.zeros((0, D))
	if verbose:
		print(f"Lattice sites: {len(ints):,} candidates, {len(kept_z):,} within r_z of the image")
		sys.stdout.flush()

		#4. invert the flow, keep physical points
	th_chunks = []
	for i in range(0, len(kept_z), 200_000):
		with torch.no_grad():
			th, _ = flow.inverse(torch.from_numpy(kept_z[i:i+200_000].astype(np.float32)))
		th_chunks.append(th.numpy())
	theta = np.vstack(th_chunks) if th_chunks else np.zeros((0, D))

		#NOTE: with an embedding the inverse lands on the embedded
		#space; lattice placement currently supports identity embeddings only.
		#Sites inverting OUTSIDE the physical space are DROPPED, not clamped:
		#clamping piles many sites onto the same boundary face, destroying the
		#lattice structure (and creating coincident templates). The resulting
		#boundary shell is instead covered by an optional stochastic fill,
		#which is the standard hybrid ("geometric + stochastic") treatment.
	keep = np.all((theta >= lo) & (theta <= hi), axis=1)
	if valid_fn is not None:
		keep &= valid_fn(theta)
	templates = theta[keep].astype(np.float32)
	if verbose:
		print(f"Lattice interior: {len(templates):,} templates "
		      f"({(~keep).sum():,} sites dropped as outside the space)")
		sys.stdout.flush()

	if fill_boundary:
			#stochastic pass seeded with the lattice: it can only add templates
			#where the lattice left gaps, i.e. the boundary shell
		from .placement import greedy_placement
		n_lat = len(templates)
		templates = greedy_placement(
			flow, r_z, lo, hi, embed_fn=embed_fn, valid_fn=valid_fn,
			batch=fill_batch, stop_acceptance=fill_stop_acceptance,
			seed=seed + 1, initial_templates=templates, verbose=verbose)
		if verbose:
			print(f"Boundary fill added {len(templates) - n_lat:,} templates")
			sys.stdout.flush()

	if verbose: print(f"Lattice bank: {len(templates):,} templates")
	return templates
